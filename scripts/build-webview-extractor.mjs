// Bundles webview-extractor/ (youtubei.js + bgutils-js + glue) into a single
// script and writes it as a string constant the app injects into its hidden
// WebView. Runs on postinstall, so updating youtubei.js / bgutils-js and
// reinstalling is enough to pick up their fixes.
import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'services', 'generated', 'webviewExtractor.ts');

const result = await build({
  entryPoints: [join(root, 'webview-extractor', 'index.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  // iOS deploymentTarget is 15.1; Android System WebView updates itself
  target: ['safari15', 'chrome90'],
  define: { global: 'globalThis' },
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;
await mkdir(dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  '// Generated by scripts/build-webview-extractor.mjs. Do not edit.\n' +
    `export const WEBVIEW_EXTRACTOR_JS = ${JSON.stringify(code)};\n`
);

console.log(`webview extractor: ${(code.length / 1024).toFixed(0)} KiB -> ${outFile}`);
